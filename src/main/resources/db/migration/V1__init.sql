-- 깜빡이리그 첫 스키마(D3). 엔티티 기준이며 ddl-auto: validate가 어긋남을 막는다.
-- 이미 적용된 마이그레이션은 고치지 않는다. 바꿀 때는 새 V{n}__*.sql을 추가한다(docs/deployment.md 4.1).
-- enum 컬럼에는 DB check 제약을 두지 않는다. 허용 값은 앱이 검증하고(D21), 값이 늘 때 마이그레이션이 필요 없게 한다.
-- 시각: Instant 컬럼은 timestamptz, BaseTimeEntity(created_at, updated_at)는 timestamp(Asia/Seoul)다.

create table app_config (
    config_key   varchar(50) not null,
    config_value text        not null,
    version      bigint      not null,
    created_at   timestamp(6) not null,
    updated_at   timestamp(6) not null,
    constraint pk_app_config primary key (config_key)
);

create table driver (
    driver_id      bigint generated by default as identity,
    nickname       varchar(12) not null,
    region_code    varchar(5)  not null,
    league_visible boolean     not null default true,
    created_at     timestamp(6) not null,
    updated_at     timestamp(6) not null,
    constraint pk_driver primary key (driver_id),
    constraint uk_driver_nickname unique (nickname)
);

create table trip (
    trip_id           varchar(36)  not null,
    driver_id         bigint       not null,
    started_at        timestamp(6) with time zone not null,
    ended_at          timestamp(6) with time zone not null,
    distance_km       float(53)    not null,
    supported_signals varchar(255) not null,
    status            varchar(20)  not null,
    score             integer,
    league_score      integer,
    created_at        timestamp(6) not null,
    updated_at        timestamp(6) not null,
    constraint pk_trip primary key (trip_id)
);
-- 오늘의 미션 라운드, 주간 리포트, 리그 기록, 최근 경기 목록
create index ix_trip_driver_ended on trip (driver_id, ended_at);
-- 주간 리포트 배치의 대상 운전자
create index ix_trip_ended on trip (ended_at);

create table trip_event (
    event_id    varchar(36) not null,
    trip_id     varchar(36) not null,
    type        varchar(20) not null,
    occurred_at timestamp(6) with time zone not null,
    payload     text,
    constraint pk_trip_event primary key (event_id),
    constraint fk_trip_event_trip foreign key (trip_id) references trip (trip_id)
);
-- 미션 · 배지의 TURN 집계, 점수 조회의 plays
create index ix_trip_event_trip_type on trip_event (trip_id, type);

create table trip_metric (
    id           bigint generated by default as identity,
    trip_id      varchar(36) not null,
    metric       varchar(30) not null,
    status       varchar(20) not null,
    reason       varchar(30),
    metric_value float(53),
    score        integer,
    weight       float(53),
    detail       varchar(500),
    constraint pk_trip_metric primary key (id),
    constraint uk_trip_metric_trip_metric unique (trip_id, metric),
    constraint fk_trip_metric_trip foreign key (trip_id) references trip (trip_id)
);

create table mission (
    mission_id     bigint generated by default as identity,
    title          varchar(40)  not null,
    period         varchar(10)  not null,
    condition_json varchar(255) not null,
    reward_point   integer      not null,
    active_from    date         not null,
    active_to      date         not null,
    created_at     timestamp(6) not null,
    updated_at     timestamp(6) not null,
    constraint pk_mission primary key (mission_id)
);

create table driver_mission (
    driver_mission_id bigint generated by default as identity,
    driver_id         bigint      not null,
    mission_id        bigint      not null,
    period_key        varchar(10) not null,
    status            varchar(20) not null,
    achieved_at       timestamp(6) with time zone,
    created_at        timestamp(6) not null,
    updated_at        timestamp(6) not null,
    constraint pk_driver_mission primary key (driver_mission_id),
    constraint uk_driver_mission_period unique (driver_id, mission_id, period_key)
);
-- 연속 기록 · 배지(달성한 날 목록)
create index ix_driver_mission_driver_status on driver_mission (driver_id, status);

create table point_ledger (
    ledger_id   bigint generated by default as identity,
    driver_id   bigint      not null,
    reason      varchar(20) not null,
    ref_id      varchar(64) not null,
    amount      integer     not null,
    distance_km float(53),
    score       integer,
    earned_at   timestamp(6) with time zone not null,
    created_at  timestamp(6) not null,
    updated_at  timestamp(6) not null,
    constraint pk_point_ledger primary key (ledger_id),
    constraint uk_point_ledger_reason_ref unique (reason, ref_id)
);
-- 잔액 · 오늘 적립 · 시즌 포인트 합 · 최근 내역
create index ix_point_ledger_driver_earned on point_ledger (driver_id, earned_at);

create table badge (
    code           varchar(30)  not null,
    name           varchar(50)  not null,
    condition_text varchar(100) not null,
    rule           varchar(30)  not null,
    target         integer      not null,
    sort_order     integer      not null,
    constraint pk_badge primary key (code)
);

create table badge_award (
    badge_award_id bigint generated by default as identity,
    driver_id      bigint      not null,
    badge_code     varchar(30) not null,
    awarded_at     timestamp(6) with time zone not null,
    created_at     timestamp(6) not null,
    updated_at     timestamp(6) not null,
    constraint pk_badge_award primary key (badge_award_id),
    constraint uk_badge_award_driver_badge unique (driver_id, badge_code)
);

create table weekly_report (
    weekly_report_id bigint generated by default as identity,
    driver_id        bigint     not null,
    week_key         varchar(8) not null,
    report_json      text       not null,
    created_at       timestamp(6) not null,
    updated_at       timestamp(6) not null,
    constraint pk_weekly_report primary key (weekly_report_id),
    constraint uk_weekly_report_driver_week unique (driver_id, week_key)
);

create table weekly_mission (
    weekly_mission_id bigint generated by default as identity,
    driver_id         bigint      not null,
    week_key          varchar(8)  not null,
    metric            varchar(30) not null,
    title             varchar(50) not null,
    target            integer     not null,
    min_distance_km   float(53)   not null,
    status            varchar(20) not null,
    created_at        timestamp(6) not null,
    updated_at        timestamp(6) not null,
    constraint pk_weekly_mission primary key (weekly_mission_id),
    constraint uk_weekly_mission_driver_week unique (driver_id, week_key)
);

create table league_member (
    league_member_id bigint generated by default as identity,
    season_id        varchar(7)  not null,
    driver_id        bigint      not null,
    league_code      varchar(30) not null,
    created_at       timestamp(6) not null,
    updated_at       timestamp(6) not null,
    constraint pk_league_member primary key (league_member_id),
    constraint uk_league_member_season_driver unique (season_id, driver_id)
);

create table league_champion (
    league_champion_id bigint generated by default as identity,
    season_id          varchar(7)  not null,
    driver_id          bigint      not null,
    league_code        varchar(30) not null,
